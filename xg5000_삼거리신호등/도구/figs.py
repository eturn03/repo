def note(lines,size=26,width=1400,color=(40,40,40)):
    h=len(lines)*(size+14)+24; im=Image.new('RGB',(width,h),'white'); d=ImageDraw.Draw(im)
    for i,l in enumerate(lines): d.text((40,12+i*(size+14)),l,font=F(size),fill=color)
