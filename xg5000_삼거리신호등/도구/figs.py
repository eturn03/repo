def header(title,lines,width=1400,size=30):
    """픽셀 폭 기준 자동 줄바꿈 header"""
    from PIL import Image, ImageDraw
    fT=F(40,True); fL=F(size); maxw=width-80
    out=[]
    for l in lines:
        cur=''
        for ch in l:
            if ImageDraw.Draw(Image.new('RGB',(1,1))).textlength(cur+ch,font=fL)>maxw and cur:
                out.append(cur); cur='  '+ch.lstrip()
            else: cur+=ch
        out.append(cur)
    # 제목도 줄바꿈
    tl=[]; cur=''
    for ch in title:
        if ImageDraw.Draw(Image.new('RGB',(1,1))).textlength(cur+ch,font=fT)>width-60 and cur: tl.append(cur); cur=ch
        else: cur+=ch
    tl.append(cur)
    h=30+56*len(tl)+len(out)*(size+14)+20; im=Image.new('RGB',(width,h),'white'); d=ImageDraw.Draw(im)
    d.rectangle([0,0,width,10],fill=RED)
    for i,t in enumerate(tl): d.text((30,25+i*56),t,font=fT,fill=(20,20,20))
    y0=30+56*len(tl)+4
    for i,l in enumerate(out): d.text((40,y0+i*(size+14)),l,font=fL,fill=(40,40,40))
    return im

