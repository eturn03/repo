def bitchart(rows,width=1400,title_rows=True):
    L=540; R=width-40; rh=48; top=40; H=top+rh*len(rows)+60
    im=Image.new('RGB',(width,H),'white'); d=ImageDraw.Draw(im)
    def X(t): return L+(R-L)*t/90
    for t in [0,30,60,70,80,90]:
        d.line([(X(t),top-10),(X(t),H-50)],fill=(200,200,200),width=2)
        f=F(22,True); tw=d.textlength(f'{t}초',font=f); d.text((X(t)-tw/2,H-44),f'{t}초',font=f,fill=(30,30,30))
    for i,(name,dev,segs,col) in enumerate(rows):
        y=top+i*rh
        if name is None:
            d.line([(20,y+rh//2),(R,y+rh//2)],fill=(120,120,120),width=2); continue
        d.text((20,y+10),name,font=F(23,True),fill=(20,20,20)); d.text((410,y+13),dev,font=F(20),fill=(90,90,90))
