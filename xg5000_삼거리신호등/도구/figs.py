def table(rows,colw,size=24,head=True,width=1400):
    rh=size+22; H=rh*len(rows)+4; im=Image.new('RGB',(width,H),'white'); d=ImageDraw.Draw(im)
    x0=(width-sum(colw))//2
    for r,row_ in enumerate(rows):
        y=r*rh; x=x0
        if head and r==0: d.rectangle([x0,y,x0+sum(colw),y+rh],fill=(235,235,240))
        for c,(cell,cw) in enumerate(zip(row_,colw)):
            d.rectangle([x,y,x+cw,y+rh],outline=(180,180,180),width=2)
            d.text((x+10,y+9),str(cell),font=F(size, head and r==0),fill=(20,20,20)); x+=cw
    return im

