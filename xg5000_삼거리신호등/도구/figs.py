def lampstrip(mon,width=1300):
    names=[('P00020','북_좌회전','L'),('P00021','북_초록','G'),('P00022','북_주황','Y'),('P00023','북_빨강','R'),('P00024','남_초록','G'),('P00025','남_주황','Y'),('P00026','남_빨강','R'),('P00027','서_좌회전','L'),('P00028','서_주황','Y'),('P00029','서_빨강','R')]
    im=Image.new('RGB',(width,120),'white'); d=ImageDraw.Draw(im); cw=width//10
    for i,(dev,nm,k) in enumerate(names):
        cx=i*cw+cw//2; on=mon.get(dev,0)==1
        d.ellipse([cx-24,16,cx+24,64],fill=LAMP[k] if on else (215,215,215),outline=(60,60,60),width=2)
        f=F(20,True); tw=d.textlength(nm,font=f); d.text((cx-tw/2,70),nm,font=f,fill=(20,20,20) if on else (150,150,150))
        f=F(17); tw=d.textlength(dev,font=f); d.text((cx-tw/2,96),dev,font=f,fill=(120,120,120))
    return im
